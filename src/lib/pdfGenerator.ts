import { jsPDF } from 'jspdf';
import type { A4PageContent } from '../db/schema';

export interface PdfSlotItem {
  id: string;
  label: string;
  kind: 'image' | 'text' | 'blank' | 'cover' | 'back';
  imageDataUrl?: string;
  textContent?: string;
}

export type PagesPerSideOption = 1 | 2 | 4;

export interface ImpositionSheetOptions {
  pagesPerSide: PagesPerSideOption;
  foldVertically: boolean;
  cutVertically: boolean;
  foldHorizontally: boolean;
  cutHorizontally: boolean;
  showGuidelineMarks: boolean;
  showTinyPageId: boolean;
}

export interface SheetRenderModel {
  sheetNumber: number;
  side: 'FRONT' | 'BACK';
  subtitle: string;
  orientation: 'portrait' | 'landscape';
  cols: number;
  rows: number;
  slots: (PdfSlotItem | null)[];
}

function sanitizeFileName(name: string): string {
  return (
    name
      .trim()
      .replace(/[^a-zA-Z0-9_\-\s]/g, '')
      .replace(/\s+/g, '_') || 'ASAN_Study_Document'
  );
}

/**
 * Compiles OneNote-style A4 pages into a real multi-page A4 PDF File.
 */
export async function buildOneNoteA4Pdf(
  documentTitle: string,
  sectionName: string,
  pages: A4PageContent[]
): Promise<File> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = 210;
  const margin = 16;
  const contentWidth = pageWidth - margin * 2;

  pages.forEach((page, pageIndex) => {
    if (pageIndex > 0) doc.addPage('a4', 'portrait');

    // Subtle header strip
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(`${documentTitle} · ${sectionName}`, margin, 11);
    doc.text(`Page ${pageIndex + 1} of ${pages.length}`, pageWidth - margin, 11, {
      align: 'right',
    });
    doc.setDrawColor(226, 232, 240);
    doc.line(margin, 14, pageWidth - margin, 14);

    let y = 22;

    if (page.title) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(13);
      doc.setTextColor(15, 23, 42);
      const titleLines = doc.splitTextToSize(page.title, contentWidth);
      doc.text(titleLines, margin, y);
      y += titleLines.length * 6 + 3;
    }

    for (const block of page.blocks) {
      if (y > 276) break;

      if (block.type === 'heading') {
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(13);
        doc.setTextColor(15, 23, 42);
        const lines = doc.splitTextToSize(block.content || '', contentWidth);
        doc.text(lines, margin, y);
        y += lines.length * 6 + 3;
      } else if (block.type === 'checklist') {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(10);
        doc.setTextColor(30, 41, 59);
        const prefix = block.checked ? '[x] ' : '[ ] ';
        const lines = doc.splitTextToSize(prefix + (block.content || ''), contentWidth);
        doc.text(lines, margin, y);
        y += lines.length * 4.8 + 2;
      } else if (block.type === 'formula') {
        doc.setFont('courier', 'normal');
        doc.setFontSize(10);
        doc.setTextColor(15, 23, 42);
        const lines = doc.splitTextToSize(block.content || '', contentWidth - 6);
        const boxHeight = Math.max(8, lines.length * 4.8 + 4);
        doc.setFillColor(248, 250, 252);
        doc.setDrawColor(203, 213, 225);
        doc.rect(margin, y - 4, contentWidth, boxHeight, 'FD');
        doc.text(lines, margin + 3, y);
        y += boxHeight + 3;
      } else if (block.type === 'image' && block.content) {
        try {
          const imgProps = doc.getImageProperties(block.content);
          const ratio = imgProps.width / imgProps.height;
          let drawW = Math.min(contentWidth, 140);
          let drawH = drawW / ratio;
          if (y + drawH > 278) {
            drawH = Math.max(25, 278 - y);
            drawW = drawH * ratio;
          }
          const format = block.content.includes('image/png') ? 'PNG' : 'JPEG';
          doc.addImage(block.content, format, margin, y, drawW, drawH);
          y += drawH + 5;
        } catch {
          // Skip invalid image data safely
        }
      } else {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(block.fontSize || 10);
        doc.setTextColor(30, 41, 59);
        const lines = doc.splitTextToSize(block.content || '', contentWidth);
        doc.text(lines, margin, y);
        y += lines.length * 4.6 + 3;
      }
    }

    // Footer
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text('Generated by ASAN-Study_tool', margin, 289);
  });

  const blob = doc.output('blob');
  return new File([blob], `${sanitizeFileName(documentTitle)}.pdf`, {
    type: 'application/pdf',
  });
}

/**
 * Computes duplex A4 booklet/sheet imposition matching 1-up, 2-up (Half A4), and 4-up (Quarter A4).
 */
export function computeImpositionSheets(
  pages: PdfSlotItem[],
  options: ImpositionSheetOptions
): SheetRenderModel[] {
  const { pagesPerSide } = options;

  if (pagesPerSide === 1) {
    // 1 Page per side (Full A4 Portrait)
    return pages.map((page, idx) => ({
      sheetNumber: Math.floor(idx / 2) + 1,
      side: idx % 2 === 0 ? 'FRONT' : 'BACK',
      subtitle: `Full A4 · Page ${page.label}`,
      orientation: 'portrait',
      cols: 1,
      rows: 1,
      slots: [page],
    }));
  }

  if (pagesPerSide === 2) {
    // 2 Pages per side (Half A4 Booklet, Landscape A4)
    // Pad to multiple of 4 for saddle-stitch duplex booklet
    const totalPadded = Math.max(4, Math.ceil(pages.length / 4) * 4);
    const padded: (PdfSlotItem | null)[] = Array.from(
      { length: totalPadded },
      (_, i) => pages[i] ?? null
    );

    const sheets: SheetRenderModel[] = [];
    const numSheets = totalPadded / 4;

    for (let s = 0; s < numSheets; s++) {
      const frontLeft = padded[totalPadded - 1 - 2 * s];
      const frontRight = padded[2 * s];
      const backLeft = padded[2 * s + 1];
      const backRight = padded[totalPadded - 2 - 2 * s];

      sheets.push({
        sheetNumber: s + 1,
        side: 'FRONT',
        subtitle: `FRONT (SIDE 1) -- [${frontLeft?.label || 'Blank'} | ${frontRight?.label || 'Blank'}]`,
        orientation: 'landscape',
        cols: 2,
        rows: 1,
        slots: [frontLeft, frontRight],
      });

      sheets.push({
        sheetNumber: s + 1,
        side: 'BACK',
        subtitle: `BACK (SIDE 2) -- DUPLEX FLIP LONG EDGE -- [${backLeft?.label || 'Blank'} | ${backRight?.label || 'Blank'}]`,
        orientation: 'landscape',
        cols: 2,
        rows: 1,
        slots: [backLeft, backRight],
      });
    }
    return sheets;
  }

  // 4 Pages per side (Quarter A4 Booklet, Portrait A4 2x2 grid)
  // Group sequentially in 8-page duplex sheets (4 front + 4 back)
  const totalPadded = Math.max(8, Math.ceil(pages.length / 8) * 8);
  const padded: (PdfSlotItem | null)[] = Array.from(
    { length: totalPadded },
    (_, i) => pages[i] ?? null
  );

  const sheets: SheetRenderModel[] = [];
  const numSheets = totalPadded / 8;

  for (let s = 0; s < numSheets; s++) {
    const base = s * 8;
    const frontSlots = [padded[base], padded[base + 1], padded[base + 2], padded[base + 3]];
    const backSlots = [padded[base + 5], padded[base + 4], padded[base + 7], padded[base + 6]];

    sheets.push({
      sheetNumber: s + 1,
      side: 'FRONT',
      subtitle: `FRONT (SIDE 1) -- Quarter A4 Grid (4-Up)`,
      orientation: 'portrait',
      cols: 2,
      rows: 2,
      slots: frontSlots,
    });

    sheets.push({
      sheetNumber: s + 1,
      side: 'BACK',
      subtitle: `BACK (SIDE 2) -- DUPLEX FLIP LONG EDGE -- Quarter A4 (4-Up)`,
      orientation: 'portrait',
      cols: 2,
      rows: 2,
      slots: backSlots,
    });
  }

  return sheets;
}

/**
 * Compiles imposed A4 sheets directly into a multi-page PDF File (0.5cm / 5mm print margins).
 */
export async function buildImposedBookletPdf(
  fileName: string,
  sheets: SheetRenderModel[],
  options: ImpositionSheetOptions
): Promise<File> {
  const firstOrientation = sheets[0]?.orientation || 'landscape';
  const doc = new jsPDF({
    orientation: firstOrientation,
    unit: 'mm',
    format: 'a4',
  });

  sheets.forEach((sheet, idx) => {
    if (idx > 0) doc.addPage('a4', sheet.orientation);

    const pageW = sheet.orientation === 'landscape' ? 297 : 210;
    const pageH = sheet.orientation === 'landscape' ? 210 : 297;
    const margin = 5; // 0.5cm margins matching Print (0.5cm Margins)
    const usableW = pageW - margin * 2;
    const usableH = pageH - margin * 2;

    const cellW = usableW / sheet.cols;
    const cellH = usableH / sheet.rows;

    sheet.slots.forEach((slot, slotIdx) => {
      const col = slotIdx % sheet.cols;
      const row = Math.floor(slotIdx / sheet.cols);
      const x = margin + col * cellW;
      const y = margin + row * cellH;

      // Subtle slot border
      doc.setDrawColor(236, 240, 245);
      doc.rect(x, y, cellW, cellH);

      if (!slot || slot.kind === 'blank') {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(8);
        doc.setTextColor(203, 213, 225);
        doc.text('Blank Slot', x + cellW / 2, y + cellH / 2, { align: 'center' });
      } else if (slot.kind === 'image' && slot.imageDataUrl) {
        try {
          const pad = 4;
          const maxW = cellW - pad * 2;
          const maxH = cellH - pad * 2;
          const imgProps = doc.getImageProperties(slot.imageDataUrl);
          const imgRatio = imgProps.width / imgProps.height;
          let drawW = maxW;
          let drawH = drawW / imgRatio;
          if (drawH > maxH) {
            drawH = maxH;
            drawW = drawH * imgRatio;
          }
          const drawX = x + (cellW - drawW) / 2;
          const drawY = y + (cellH - drawH) / 2;
          const fmt = slot.imageDataUrl.includes('image/png') ? 'PNG' : 'JPEG';
          doc.addImage(slot.imageDataUrl, fmt, drawX, drawY, drawW, drawH);
        } catch {
          // fallback if image fails
        }
      } else if (slot.kind === 'text') {
        // Explicit 10pt font size in a page-length placeholder as requested!
        const pad = 6;
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(10);
        doc.setTextColor(15, 23, 42);
        const lines = doc.splitTextToSize(slot.textContent || '', cellW - pad * 2);
        const lineHeightMm = 4.2;
        const maxLines = Math.floor((cellH - pad * 2) / lineHeightMm);
        doc.text(lines.slice(0, maxLines), x + pad, y + pad + 3.5);
      } else {
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(10);
        doc.setTextColor(148, 163, 184);
        doc.text(
          `${slot.label}${slot.kind === 'cover' ? ' (Front Cover)' : slot.kind === 'back' ? ' (Back Cover)' : ''}`,
          x + cellW / 2,
          y + cellH / 2,
          { align: 'center' }
        );
      }

      if (options.showTinyPageId && slot) {
        doc.setFillColor(15, 23, 42);
        doc.rect(x + cellW - 9, y + cellH - 5.5, 8, 4.5, 'F');
        doc.setFont('courier', 'bold');
        doc.setFontSize(6.5);
        doc.setTextColor(255, 255, 255);
        doc.text(slot.label, x + cellW - 5, y + cellH - 2.3, { align: 'center' });
      }
    });

    if (options.showGuidelineMarks) {
      doc.setDrawColor(148, 163, 184);
      doc.setLineDashPattern([2, 2], 0);
      if (options.foldVertically || options.cutVertically) {
        doc.line(pageW / 2, 0, pageW / 2, pageH);
      }
      if (options.foldHorizontally || options.cutHorizontally) {
        doc.line(0, pageH / 2, pageW, pageH / 2);
      }
      doc.setLineDashPattern([], 0);
    }
  });

  const blob = doc.output('blob');
  return new File([blob], `${sanitizeFileName(fileName)}.pdf`, {
    type: 'application/pdf',
  });
}

export async function shareOrDownloadPdf(
  file: File,
  title: string
): Promise<'shared' | 'downloaded'> {
  if (
    typeof navigator !== 'undefined' &&
    typeof navigator.share === 'function' &&
    typeof navigator.canShare === 'function' &&
    navigator.canShare({ files: [file] })
  ) {
    try {
      await navigator.share({
        title,
        text: `Shared from ASAN-Study_tool: ${title}`,
        files: [file],
      });
      return 'shared';
    } catch (err) {
      if ((err as Error).name === 'AbortError') {
        return 'shared';
      }
    }
  }

  const url = URL.createObjectURL(file);
  const a = document.createElement('a');
  a.href = url;
  a.download = file.name;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
  return 'downloaded';
}
